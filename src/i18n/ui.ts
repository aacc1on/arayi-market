export type UIKey = keyof (typeof ui)['hy'];

export function t(lang: Lang, key: UIKey): string {
  return (ui[lang] as Record<string, string>)[key] ?? (ui.hy as Record<string, string>)[key] ?? key;
}

/** Localized field from a flat record (title_hy, title_en, title_ru), falling back to hy then en. */
export function pick(obj: Record<string, unknown>, field: string, lang: Lang): string {
  const v = (l: string) => String((obj[`${field}_${l}`] as string) ?? '').trim();
  return v(lang) || v('hy') || v('en');
}

export function originName(lang: Lang, code: string): string {
  if (!code) return '';
  const key = `origin.${code}` as UIKey;
  const name = t(lang, key);
  return name === key ? code : name;
}

export const path = {
  home: (l: Lang) => `/${l}/`,
  catalog: (l: Lang) => `/${l}/catalog/`,
  category: (l: Lang, slug: string) => `/${l}/c/${slug}/`,
  product: (l: Lang, slug: string) => `/${l}/p/${slug}/`,
  rfq: (l: Lang, product?: string) => `/${l}/rfq/` + (product ? `?product=${encodeURIComponent(product)}` : ''),
  search: (l: Lang) => `/${l}/search/`,
};

/** Swap the language prefix of a path: /hy/p/x/ -> /en/p/x/ */
export function switchLang(pathname: string, to: Lang): string {
  const parts = pathname.split('/');
  if (LANGS.includes(parts[1] as Lang)) parts[1] = to;
  else return `/${to}/`;
  return parts.join('/');
}
